export const LEGACY_DAY_22: DayPlan = DAY_22;
export const LEGACY_TOTAL_DAYS = 22;

/** Plan for a 1-based legacy day number (1-22). */
export function legacyPlanForDay(day: number): DayPlan {
  if (day >= LEGACY_TOTAL_DAYS) return LEGACY_DAY_22;
  return LEGACY_WEEK[(day - 1) % 7];
}